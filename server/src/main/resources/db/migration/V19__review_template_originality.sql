-- M9 评审模板增强：新增「原创性与信息增量」评估维度（不单独计分，作为文字结论保留在 suggestion），
-- 并要求 AI 在无法可靠评价时在结论标注低置信度，供 ReviewService 识别转人工复核。
UPDATE prompt_template
SET content = '请从可读性、结构完整性、关键词密度、SEO 友好度四个维度评价以下文章（各 0-100 分），并额外评估「原创性与信息增量」：判断是否存在洗稿式堆砌、空洞无信息增量的段落（此维度不单独打分，用 2-3 句话给出结论）。指出主要问题并给出修改建议，最后给出总分（0-100，取四维均分）与一句话结论。若文章过短或任一维度无法可靠评价，请在结论末尾追加「（低置信度，建议人工复核）」。输出格式：\n可读性：X分\n结构完整性：X分\n关键词密度：X分\nSEO 友好度：X分\n原创性与信息增量：<结论>\n问题与建议：...\n总分：X\n结论：...\n\n文章：\n{{content}}',
    updated_at = NOW()
WHERE category = 'review';
